#!/usr/bin/env node
// Validates the study memory in memory/ (conventions: .claude/rules/memory-layer.md).
//   memory/pyq/papers/<paper>.json             one official GATE CSE paper: all 65 questions, keys, chapters
//   memory/chapters/<chapter>/gate_pyqs.json   that chapter's PYQs, solved step by step
//   memory/chapters/<chapter>/derivations.md   that chapter's proofs and derivations
//   memory/STATUS.md                           progress table, generated
//
//   node scripts/check-memory.mjs                  everything; stale STATUS.md or CLAUDE.md chapter map fails
//   node scripts/check-memory.mjs --write          the same, then regenerates both when valid
//   node scripts/check-memory.mjs --chapter <id>   one chapter's files against the ledger (repeatable)
//   node scripts/check-memory.mjs --paper <id>     one ledger file only (repeatable)
//   --memory <dir> --data <dir> --claude <file>    alternative locations, for tests
// Exits 1 on any error. Proven to fail on bad input: scripts/test-check-memory.mjs.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDerivations, slugify, tokenizeMath } from './lib/derivations.mjs';
import { MSQ_FROM, PAPERS, PAPER_ID, keyAccepts, parseKey, parseQuestionId, positionMarks, questionId } from './lib/pyq.mjs';
import { createChecker, isInt, isStr, isUrl } from './lib/rules.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const values = (name) => args.flatMap((a, i) => (a === name ? [args[i + 1]] : []));
const onlyChapters = values('--chapter');
const onlyPapers = values('--paper');
const memoryDir = values('--memory')[0] ?? join(root, 'memory');
const dataDir = values('--data')[0] ?? join(root, 'data');
const claudeFile = values('--claude')[0] ?? join(root, 'CLAUDE.md');
const diagramDir = join(values('--diagrams')[0] ?? join(root, 'public/diagrams'), 'pyq');
const writeGenerated = args.includes('--write');
const fullRun = !onlyChapters.length && !onlyPapers.length;

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const { subjects } = readJson(join(root, 'data/subjects.json'));
const chapters = new Map(subjects.flatMap((s) => s.chapters.map((c) => [c.id, { ...c, subject: s.code }])));

const { errors, fail, checkTex, checkInline, checkBanned, checkText, checkList } = createChecker({ tells: true });

const TYPES = ['mcq', 'msq', 'nat'];
const SECTIONS = ['GA', 'CS'];
const DIFFICULTY = ['easy', 'medium', 'hard'];
const CODE_LANG = /^[a-z0-9+#-]+$/;
const QUESTIONS_PER_PAPER = 65;
const MARKS_PER_PAPER = 100;
const MIN_SECTIONS = 3;
const MIN_SECTION_CHARS = 300;
const CHAPTER_FILES = ['derivations.md', 'gate_pyqs.json'];
const MAP_START = '<!-- chapter-map:start (generated by npm run memory) -->';
const MAP_END = '<!-- chapter-map:end -->';

const papers = new Map();
const ledger = new Map();
const solved = new Set();
const chapterProgress = new Map();
const derivationCounts = new Map();

const contentCache = new Map();
function chapterTopics(id) {
  if (!contentCache.has(id)) {
    const file = join(dataDir, 'chapters', `${id}.json`);
    contentCache.set(id, existsSync(file) ? new Set(readJson(file).topics.map((t) => t.id)) : null);
  }
  return contentCache.get(id);
}

function checkSource(where, source) {
  if (!source || typeof source !== 'object') return fail(where, 'expected { label, url }');
  checkText(`${where}.label`, source.label, { max: 120, math: false });
  if (!isUrl(source.url)) fail(`${where}.url`, 'expected an https URL');
}

// ---------------------------------------------------------------- ledger

function checkPaper(file) {
  const id = file.replace(/\.json$/, '');
  const at = `pyq/papers/${file}`;
  const m = PAPER_ID.exec(id);
  if (!m || !PAPERS.includes(id)) return fail(at, `"${id}" is not one of the ${PAPERS.length} papers in scripts/lib/pyq.mjs`);
  let p;
  try {
    p = readJson(join(memoryDir, 'pyq/papers', file));
  } catch (e) {
    return fail(at, `invalid JSON: ${e.message}`);
  }
  const year = Number(m[1]);
  const set = m[2] ? Number(m[2]) : null;
  if (p.paper !== id) fail(at, `paper "${p.paper}" does not match the file name`);
  if (p.year !== year) fail(at, `year must be ${year}`);
  if (p.set !== set) fail(at, `set must be ${set}`);
  checkText(`${at}.title`, p.title, { max: 80, math: false });
  checkSource(`${at}.sources.key`, p.sources?.key);
  for (const k of ['paper', 'index']) if (p.sources?.[k] !== undefined) checkSource(`${at}.sources.${k}`, p.sources[k]);

  let marks = 0;
  checkList(`${at}.questions`, p.questions, 0, (q, w) => {
    if (!SECTIONS.includes(q.section)) return fail(w, `section must be one of ${SECTIONS}`);
    const expected = isInt(q.n) ? positionMarks(year, q.section, q.n) : null;
    if (expected === null) return fail(w, `${q.section} ${q.n} is not a question number of a ${year} paper`);
    const qid = questionId(id, q.section, q.n);
    if (ledger.has(qid)) return fail(w, `duplicate question ${q.section} ${q.n}`);
    if (q.marks !== expected) fail(w, `${q.section} ${q.n} carries ${expected} mark(s), not ${q.marks}`);
    marks += expected;
    if (!TYPES.includes(q.type)) return fail(w, `type must be one of ${TYPES}`);
    if (q.type === 'msq' && year < MSQ_FROM) fail(w, `MSQ did not exist before ${MSQ_FROM}`);
    const key = parseKey(q.key, q.type);
    if (!key) fail(w, `key "${q.key}" is not a valid ${q.type} key (syntax: scripts/lib/pyq.mjs)`);
    if (q.chapter === null) checkText(`${w}.note`, q.note, { min: 10, max: 300, math: false });
    else if (!chapters.has(q.chapter)) fail(w, `chapter "${q.chapter}" does not exist`);
    else if ((q.section === 'GA') !== q.chapter.startsWith('ga-')) fail(w, `${q.section} question mapped to ${q.chapter}`);
    else if (q.note !== undefined) checkText(`${w}.note`, q.note, { min: 10, max: 300, math: false });
    if (!isUrl(q.url)) fail(`${w}.url`, 'expected the https URL of the question page');
    if (q.go !== undefined && !isInt(q.go)) fail(`${w}.go`, 'GATE Overflow id must be an integer');
    if (q.tags !== undefined) checkList(`${w}.tags`, q.tags, 0, (t, tw) => isStr(t) || fail(tw, 'tag must be text'));
    ledger.set(qid, { ...q, id: qid, paper: id, parsedKey: key });
  });
  const count = Array.isArray(p.questions) ? p.questions.length : 0;
  if (count !== QUESTIONS_PER_PAPER) fail(`${at}.questions`, `a GATE CSE paper has ${QUESTIONS_PER_PAPER} questions, got ${count}`);
  else if (marks !== MARKS_PER_PAPER) fail(at, `marks add up to ${marks}, expected ${MARKS_PER_PAPER}`);
  papers.set(id, { id, year, set, count });
}

// ---------------------------------------------------------------- solved PYQs

function checkTable(w, table) {
  if (!Array.isArray(table?.headers) || !table.headers.length) return fail(w, 'table needs headers');
  table.headers.forEach((h, i) => checkText(`${w}.headers[${i}]`, h, { max: 80 }));
  checkList(`${w}.rows`, table.rows, 1, (row, rw) => {
    if (!Array.isArray(row) || row.length !== table.headers.length) return fail(rw, `row needs ${table.headers.length} cells`);
    row.forEach((cell, i) => {
      if (typeof cell !== 'string') fail(`${rw}[${i}]`, 'cell must be text');
      else if (cell) checkText(`${rw}[${i}]`, cell, { max: 200 });
    });
  });
}

function answerShapeOk(q) {
  if (q.type === 'nat') return typeof q.answer === 'number' && Number.isFinite(q.answer);
  if (q.type === 'mcq') return isInt(q.answer) && q.answer >= 0 && q.answer < 4;
  return Array.isArray(q.answer) && q.answer.length >= 1 && new Set(q.answer).size === q.answer.length
    && q.answer.every((a) => isInt(a) && a >= 0 && a < 4);
}

function checkSolution(w, q, key) {
  const s = q.solution ?? {};
  checkList(`${w}.solution.steps`, s.steps, 2, (step, sw) => {
    checkText(`${sw}.title`, step.title, { max: 90 });
    checkText(`${sw}.body`, step.body, { min: 20, max: 2000 });
    if (step.tex !== undefined) checkTex(`${sw}.tex`, step.tex);
  });
  if (!s.shortcut || typeof s.shortcut !== 'object') fail(`${w}.solution.shortcut`, 'needs the exam-hall shortcut { body, tex? }');
  else {
    checkText(`${w}.solution.shortcut.body`, s.shortcut.body, { min: 20, max: 1000 });
    if (s.shortcut.tex !== undefined) checkTex(`${w}.solution.shortcut.tex`, s.shortcut.tex);
  }
  checkList(`${w}.solution.traps`, s.traps, 1, (trap, tw) => {
    checkText(`${tw}.text`, trap.text, { min: 20, max: 700 });
    if (trap.option === undefined) return;
    if (q.type === 'nat' || !(isInt(trap.option) && trap.option >= 0 && trap.option < 4)) fail(`${tw}.option`, 'option must index one of the 4 options');
    else if (q.type === 'mcq' && key?.accepted?.includes(trap.option)) fail(`${tw}.option`, 'a trap option cannot be a correct answer');
  });
}

const HINT_KINDS = ['guide', 'concept', 'principle', 'setup', 'partial'];

/**
 * The learner's ladder: each hint is one rung higher than the last, never repeats a step, and
 * never states the answer. Hints are optional per question; when present they must be a ladder.
 */
function checkHints(w, q) {
  if (q.hints === undefined) return;
  checkList(`${w}.hints`, q.hints, 3, (h, hw) => {
    if (!HINT_KINDS.includes(h?.kind)) fail(`${hw}.kind`, `kind must be one of ${HINT_KINDS}`);
    checkText(`${hw}.text`, h.text, { min: 20, max: 600 });
    if (h.tex !== undefined) checkTex(`${hw}.tex`, h.tex);
    if (isStr(h.text) && /\b(the )?(correct |final )?answer is\b/i.test(h.text)) fail(`${hw}.text`, 'a hint may not state the answer');
  });
  if (!Array.isArray(q.hints)) return;
  if (q.hints.length > 5) fail(`${w}.hints`, 'at most 5 hints');
  const order = q.hints.map((h) => HINT_KINDS.indexOf(h?.kind));
  if (order.some((k, i) => i > 0 && k <= order[i - 1])) fail(`${w}.hints`, 'hints must climb the ladder in order, one rung each: guide, concept, principle, setup, partial');
  const bodies = new Set((q.solution?.steps ?? []).map((st) => st?.body));
  const texts = q.hints.map((h) => h?.text);
  if (new Set(texts).size !== texts.length || texts.some((t) => bodies.has(t))) fail(`${w}.hints`, 'a hint may not repeat another hint or a solution step');
}

/** A generated practice variation: same method, new numbers, labelled as ours in the app. */
function checkVariation(w, q) {
  const v = q.variation;
  if (v === undefined) return;
  checkText(`${w}.variation.stem`, v?.stem, { min: 15, max: 1500 });
  checkText(`${w}.variation.explanation`, v?.explanation, { min: 30, max: 1500 });
  if (q.type === 'nat') {
    if (v.options !== undefined) fail(`${w}.variation.options`, 'nat variations take no options');
    if (typeof v.answer !== 'number' || !Number.isFinite(v.answer)) fail(`${w}.variation.answer`, 'nat variation answer must be a finite number');
    return;
  }
  if (!Array.isArray(v.options) || v.options.length !== 4 || new Set(v.options).size !== 4) return fail(`${w}.variation.options`, 'needs 4 distinct options');
  v.options.forEach((o, i) => checkText(`${w}.variation.options[${i}]`, o, { max: 800 }));
  if (!answerShapeOk({ type: q.type, answer: v.answer })) fail(`${w}.variation.answer`, 'answer must match the question type');
  else if (q.type === 'mcq' && v.answer === q.answer && v.stem === q.stem) fail(`${w}.variation`, 'a variation may not copy the question');
}

/** Why this concept applies: the clues in the wording, and the topic that teaches it. */
function checkRecognize(w, q, topics) {
  const r = q.solution?.recognize;
  if (r === undefined) return;
  if (!topics.has(r?.concept)) fail(`${w}.solution.recognize.concept`, `"${r?.concept}" is not a topic of this chapter`);
  checkText(`${w}.solution.recognize.clues`, r?.clues, { min: 30, max: 800 });
  if (r.contrast !== undefined) checkText(`${w}.solution.recognize.contrast`, r.contrast, { min: 30, max: 800 });
}

function checkCheck(w, q) {
  const c = q.solution?.check;
  if (c === undefined) return;
  checkText(`${w}.solution.check.body`, c?.body, { min: 20, max: 800 });
  if (c.tex !== undefined) checkTex(`${w}.solution.check.tex`, c.tex);
}

const diagramsUsed = new Set();

/** The SVG is inlined as an <img>, so it must stand alone: a title, a viewBox, no script and no remote fetch. */
function checkDiagram(w, diagram, name) {
  checkText(`${w}.alt`, diagram?.alt, { min: 15, max: 400 });
  const file = join(diagramDir, name);
  diagramsUsed.add(name);
  if (!existsSync(file)) return fail(w, `public/diagrams/pyq/${name} does not exist`);
  const svg = readFileSync(file, 'utf8');
  if (!/^\s*(<\?xml[^>]*>\s*)?<svg[\s>]/.test(svg) || !/<\/svg>\s*$/.test(svg)) fail(w, `${name} is not a single <svg> document`);
  if (!/<svg[^>]*\sviewBox="[\d.\s-]+"/.test(svg)) fail(w, `${name} needs a viewBox so it scales`);
  if (!/<title>[^<]{5,}<\/title>/.test(svg)) fail(w, `${name} needs a <title>`);
  if (/<script|\son\w+\s*=|(?:xlink:)?href\s*=\s*["'](?!#)|<foreignObject/i.test(svg)) fail(w, `${name} may not carry scripts, event handlers, external links or foreignObject`);
  if (svg.length > 60_000) fail(w, `${name} is ${svg.length} bytes; keep a diagram under 60 kB`);
}

function checkSolvedQuestion(w, q, entry, topics) {
  if (!topics.has(q.topic)) fail(`${w}.topic`, `"${q.topic}" is not a topic of this chapter`);
  checkText(`${w}.stem`, q.stem, { min: 15, max: 3000 });
  if (q.code !== undefined) {
    if (!CODE_LANG.test(q.code?.lang ?? '')) fail(`${w}.code.lang`, 'expected a language name such as c');
    if (!isStr(q.code?.text) || q.code.text.length > 5000) fail(`${w}.code.text`, 'expected code of at most 5000 chars');
  }
  if (q.table !== undefined) checkTable(`${w}.table`, q.table);
  if (q.figure !== undefined) checkText(`${w}.figure`, q.figure, { min: 20, max: 1500 });
  // A figure in words is hard to solve from, so every figure question also ships the drawing.
  if (q.figure !== undefined && q.diagram === undefined) fail(`${w}.diagram`, `a question with a figure needs its drawing at public/diagrams/pyq/${q.id}.svg`);
  if (q.diagram !== undefined) checkDiagram(`${w}.diagram`, q.diagram, `${q.id}.svg`);
  if (q.solutionDiagram !== undefined) checkDiagram(`${w}.solutionDiagram`, q.solutionDiagram, `${q.id}-solution.svg`);
  if (q.type === 'nat') {
    if (q.options !== undefined) fail(w, 'nat questions take no options');
  } else if (!Array.isArray(q.options) || q.options.length !== 4) {
    fail(`${w}.options`, 'mcq/msq need exactly 4 options');
  } else {
    q.options.forEach((o, i) => checkText(`${w}.options[${i}]`, o, { max: 800 }));
    if (new Set(q.options).size !== 4) fail(`${w}.options`, 'options must be distinct');
  }
  const shapeOk = answerShapeOk(q);
  if (!shapeOk) fail(`${w}.answer`, { nat: 'nat answer must be a finite number', mcq: 'mcq answer must be an option index 0–3', msq: 'msq answer must be 1–4 distinct option indices' }[q.type]);
  if ('tolerance' in q) fail(`${w}.tolerance`, 'PYQs score with the official key range; drop tolerance');
  // Our derived answer must earn the marks under the official key, or keyNote must say why not.
  const key = entry.parsedKey;
  if (key?.mta && !isStr(q.keyNote)) fail(`${w}.keyNote`, 'a marks-to-all question needs a keyNote naming the flaw');
  if (key && !key.mta && shapeOk && !keyAccepts(key, q.type, q.answer) && !isStr(q.keyNote)) {
    fail(`${w}.answer`, `answer disagrees with the official key "${entry.key}": fix it, or explain the dispute in keyNote`);
  }
  if (q.keyNote !== undefined) checkText(`${w}.keyNote`, q.keyNote, { min: 30, max: 1200 });
  checkSolution(w, q, key);
  checkHints(w, q);
  checkVariation(w, q);
  checkRecognize(w, q, topics);
  checkCheck(w, q);
  if (!DIFFICULTY.includes(q.difficulty)) fail(`${w}.difficulty`, `difficulty must be one of ${DIFFICULTY}`);
  checkList(`${w}.sources`, q.sources, 1, (src, sw) => checkSource(sw, src));
}

function checkPyqs(chapterId) {
  const at = `chapters/${chapterId}/gate_pyqs.json`;
  const topics = chapterTopics(chapterId);
  if (!topics) return fail(at, `data/chapters/${chapterId}.json does not exist yet; write the chapter first`);
  let doc;
  try {
    doc = readJson(join(memoryDir, 'chapters', chapterId, 'gate_pyqs.json'));
  } catch (e) {
    return fail(at, `invalid JSON: ${e.message}`);
  }
  if (doc.chapter !== chapterId) fail(at, `chapter "${doc.chapter}" does not match the folder`);
  const processed = new Set();
  checkList(`${at}.papers`, doc.papers, 1, (p, w) => {
    if (!papers.has(p)) fail(w, `paper "${p}" is not in the ledger`);
    if (processed.has(p)) fail(w, `paper "${p}" is listed twice`);
    processed.add(p);
  });
  const done = new Set();
  const claim = (w, id) => {
    const entry = ledger.get(id);
    if (!entry) return fail(w, `"${id}" is not a question in the ledger`);
    if (done.has(id)) return fail(w, `"${id}" appears twice`);
    done.add(id);
    if (entry.chapter !== chapterId) fail(w, `the ledger maps ${id} to ${entry.chapter ?? 'no chapter'}`);
    if (!processed.has(entry.paper)) fail(w, `${entry.paper} is not listed in papers`);
    return entry;
  };
  checkList(`${at}.questions`, doc.questions, 0, (q, w) => {
    const entry = claim(w, q.id);
    if (!entry) return;
    for (const k of ['type', 'marks', 'key']) if (q[k] !== entry[k]) fail(`${w}.${k}`, `"${q[k]}" differs from the ledger's "${entry[k]}"`);
    checkSolvedQuestion(w, q, entry, topics);
    solved.add(q.id);
  });
  checkList(`${at}.skipped`, doc.skipped ?? [], 0, (s, w) => {
    if (claim(w, s.id)) checkText(`${w}.reason`, s.reason, { min: 15, max: 300 });
  });
  // Every question the ledger gives this chapter, from every paper declared done, is solved or skipped.
  for (const entry of ledger.values()) {
    if (entry.chapter === chapterId && processed.has(entry.paper) && !done.has(entry.id)) {
      fail(at, `${entry.id} (${entry.section} ${entry.n}) is mapped here but neither solved nor skipped`);
    }
  }
  chapterProgress.set(chapterId, { solved: doc.questions?.length ?? 0, skipped: doc.skipped?.length ?? 0, papers: processed.size });
}

// ---------------------------------------------------------------- derivations

function checkMarkdown(w, body) {
  const { tokens, error } = tokenizeMath(body);
  if (error) return fail(w, error);
  for (const t of tokens) {
    if (t.kind === 'inline') checkInline(w, t.value);
    else if (t.kind === 'display') checkTex(w, t.value);
    else if (!t.code) {
      const prose = t.value.replace(/`[^`]*`/g, '');
      checkBanned(w, prose);
      if (/\\\(|\\\[/.test(prose)) fail(w, 'write math as $…$ or $$…$$, not \\( or \\[');
      const tag = /<!--|<\/?[a-z][\w-]*(\s[^<>]*)?\/?>/i.exec(prose);
      if (tag) fail(w, `raw HTML "${tag[0]}" is not allowed; write markdown (or put a < inside $…$)`);
    }
  }
}

function checkDerivations(chapterId) {
  const at = `chapters/${chapterId}/derivations.md`;
  const topics = chapterTopics(chapterId);
  if (!topics) return fail(at, `data/chapters/${chapterId}.json does not exist yet; write the chapter first`);
  const doc = parseDerivations(readFileSync(join(memoryDir, 'chapters', chapterId, 'derivations.md'), 'utf8'));
  if (!doc.title) fail(at, 'the first line must be the "# " title');
  else checkText(`${at} title`, doc.title, { max: 100 });
  for (const h of doc.extraTitles) fail(`${at}:${h.line}`, 'only the first line is a "# " heading; sections use "## "');
  if (doc.sections.length < MIN_SECTIONS) fail(at, `expected at least ${MIN_SECTIONS} "## " sections, got ${doc.sections.length}`);
  if (doc.intro) checkMarkdown(`${at} intro`, doc.intro);
  const slugs = new Set();
  for (const s of doc.sections) {
    const w = `${at}:${s.line} "${s.title}"`;
    const slug = slugify(s.title);
    if (!slug) fail(w, 'title needs letters or digits');
    if (slugs.has(slug)) fail(w, 'duplicate section title');
    slugs.add(slug);
    checkText(`${w} title`, s.title, { max: 100 });
    if (!s.topics) fail(w, 'the line after the heading must be <!-- topics: <topic id>, … -->');
    else if (!s.topics.length) fail(w, 'list at least one topic');
    else for (const t of s.topics) if (!topics.has(t)) fail(w, `topic "${t}" is not a topic of ${chapterId}`);
    if (!s.body.includes('**Claim.**')) fail(w, 'needs a **Claim.** paragraph');
    if (!/\*\*(Proof|Derivation)\.\*\*/.test(s.body)) fail(w, 'needs a **Proof.** or **Derivation.** paragraph');
    if (s.body.length < MIN_SECTION_CHARS) fail(w, `section is ${s.body.length} chars; a derivation needs at least ${MIN_SECTION_CHARS}`);
    checkMarkdown(w, s.body);
  }
  derivationCounts.set(chapterId, doc.sections.length);
}

// ---------------------------------------------------------------- generated files

function statusMarkdown() {
  const all = [...ledger.values()];
  const present = PAPERS.filter((p) => papers.has(p));
  const lines = [
    '# Memory status',
    '',
    'Generated by `npm run memory`; `npm run check:memory` fails when this file is out of date.',
    '',
    '## PYQ ledger',
    '',
    `${present.length} of ${PAPERS.length} papers, ${all.length} questions, ${all.filter((q) => q.chapter).length} mapped to a chapter, ${all.filter((q) => q.key === 'MTA').length} marks-to-all, ${solved.size} solved.`,
    '',
    '| Paper | Questions | Mapped | Solved |',
    '|---|---:|---:|---:|',
  ];
  for (const p of PAPERS) {
    const qs = all.filter((q) => q.paper === p);
    lines.push(papers.has(p) ? `| ${p} | ${qs.length} | ${qs.filter((q) => q.chapter).length} | ${qs.filter((q) => solved.has(q.id)).length} |` : `| ${p} | missing | | |`);
  }
  lines.push('', '## Chapters', '', '| Chapter | Content | Derivations | Solved | Skipped | Mapped | Papers done |', '|---|---|---:|---:|---:|---:|---:|');
  for (const id of chapters.keys()) {
    const progress = chapterProgress.get(id);
    const mapped = all.filter((q) => q.chapter === id).length;
    lines.push(`| ${id} | ${chapterTopics(id) ? 'ready' : 'pending'} | ${derivationCounts.get(id) ?? '–'} | ${progress?.solved ?? '–'} | ${progress?.skipped ?? '–'} | ${mapped} | ${progress ? `${progress.papers}/${present.length}` : '–'} |`);
  }
  return `${lines.join('\n')}\n`;
}

function chapterMapMarkdown() {
  const rows = ['| Ref | Chapter id | Title | Subject |', '|---|---|---|---|'];
  for (const s of subjects) for (const c of s.chapters) rows.push(`| ${c.ref} | \`${c.id}\` | ${c.title} | ${s.code} |`);
  return `${MAP_START}\n${rows.join('\n')}\n${MAP_END}`;
}

function replaceChapterMap(text) {
  const start = text.indexOf(MAP_START);
  const end = text.indexOf(MAP_END);
  if (start < 0 || end < start) return null;
  return text.slice(0, start) + chapterMapMarkdown() + text.slice(end + MAP_END.length);
}

function checkGenerated() {
  const statusFile = join(memoryDir, 'STATUS.md');
  const status = statusMarkdown();
  const claude = existsSync(claudeFile) ? readFileSync(claudeFile, 'utf8') : null;
  const claudeNext = claude === null ? null : replaceChapterMap(claude);
  if (claudeNext === null) return fail('CLAUDE.md', `needs the chapter map block between "${MAP_START}" and "${MAP_END}"`);
  if (writeGenerated) {
    mkdirSync(memoryDir, { recursive: true });
    writeFileSync(statusFile, status);
    if (claudeNext !== claude) writeFileSync(claudeFile, claudeNext);
    return;
  }
  if (!existsSync(statusFile) || readFileSync(statusFile, 'utf8') !== status) fail('memory/STATUS.md', 'out of date: run npm run memory');
  if (claudeNext !== claude) fail('CLAUDE.md', 'the chapter map is out of date: run npm run memory');
}

