// The service worker's source, filled in at build time with the bundle's file list, so it can
// precache the app shell on install and fetch the rest only when the learner asks for it.
import { createHash } from 'node:crypto';

/**
 * @param {{ shell: string[]; all: { file: string; bytes: number }[] }} files paths relative to dist/
 */
export function serviceWorkerSource({ shell, all }) {
  const version = createHash('sha256').update(all.map((f) => `${f.file}:${f.bytes}`).join('\n')).digest('hex').slice(0, 12);
  const totalBytes = all.reduce((s, f) => s + f.bytes, 0);
  return `// Generated by vite.config.ts from scripts/lib/service-worker.mjs; do not edit.
const VERSION = 'gate-atlas-${version}';
const SHELL = ${JSON.stringify(['./', ...shell])};
const ALL = ${JSON.stringify(all.map((f) => f.file))};
const TOTAL_BYTES = ${totalBytes};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(VERSION).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gate-atlas-') && k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // The page itself: fresh when online, so a new deploy shows at once; the cached shell offline.
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  // Every other file name carries a content hash, so a cached copy is never stale.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(VERSION).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});

async function status() {
  const cache = await caches.open(VERSION);
  const keys = new Set((await cache.keys()).map((r) => new URL(r.url).pathname));
  const base = new URL('./', self.registration.scope).pathname;
  const cached = ALL.filter((f) => keys.has(base + f)).length;
  return { type: 'offline-status', cached, total: ALL.length, totalBytes: TOTAL_BYTES };
}

self.addEventListener('message', (event) => {
  const reply = (msg) => event.source && event.source.postMessage(msg);
  if (event.data && event.data.type === 'offline-adopt') {
    // Files the page loaded before this worker controlled it; without this, the first visit's
    // pages would not work offline until opened a second time.
    const own = event.data.urls.filter((u) => new URL(u).origin === self.location.origin);
    event.waitUntil(caches.open(VERSION).then((c) => Promise.all(own.map((u) => c.match(u).then((hit) => hit || c.add(u).catch(() => undefined))))));
  } else if (event.data === 'offline-status') {
    event.waitUntil(status().then(reply));
  } else if (event.data === 'offline-save-all') {
    event.waitUntil(
      (async () => {
        const cache = await caches.open(VERSION);
        const BATCH = 8;
        for (let i = 0; i < ALL.length; i += BATCH) {
          await cache.addAll(ALL.slice(i, i + BATCH));
          reply({ ...(await status()), type: 'offline-progress' });
        }
        reply(await status());
      })().catch((e) => reply({ type: 'offline-error', message: String(e) })),
    );
  }
});
`;
}
