function ledgerPaper(paper, year, set, numbers) {
  const questions = [];
  for (let n = 1; n <= 10; n++) questions.push({ section: 'GA', n, type: 'mcq', marks: n <= 5 ? 1 : 2, key: 'A', chapter: null, note: 'fixture question', url: url(`ga${n}`) });
  for (const n of numbers.cs) {
    const marks = n <= numbers.oneMarkUpTo ? 1 : 2;
    questions.push({ section: 'CS', n, type: 'mcq', marks, key: 'A', chapter: null, note: 'fixture question', url: url(`q${n}`) });
  }
  return { paper, title: `Fixture ${paper}`, year, set, sources: { key: { label: 'Official key', url: url('key') } }, questions };
}

