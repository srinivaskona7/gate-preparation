function materialize(f) {
  const dir = mkdtempSync(join(tmpdir(), 'gate-memory-'));
  const mem = join(dir, 'memory');
  mkdirSync(join(mem, 'pyq/papers'), { recursive: true });
  mkdirSync(join(mem, 'chapters', CH), { recursive: true });
  for (const [id, paper] of Object.entries(f.papers)) writeFileSync(join(mem, 'pyq/papers', `${id}.json`), JSON.stringify(paper));
  writeFileSync(join(mem, 'chapters', CH, 'gate_pyqs.json'), JSON.stringify(f.pyqs));
  writeFileSync(join(mem, 'chapters', CH, 'derivations.md'), f.derivations);
  for (const [path, text] of Object.entries(f.extra)) {
    mkdirSync(dirname(join(mem, path)), { recursive: true });
    writeFileSync(join(mem, path), text);
  }
  writeFileSync(join(dir, 'CLAUDE.md'), f.claude);
  mkdirSync(join(dir, 'diagrams/pyq'), { recursive: true });
  for (const [name, svg] of Object.entries(f.diagrams)) writeFileSync(join(dir, 'diagrams/pyq', name), svg);
  return { dir, mem };
}

function run(dir, mem, extra = []) {
  try {
    const out = execFileSync('node', [join(root, 'scripts/check-memory.mjs'), '--memory', mem, '--claude', join(dir, 'CLAUDE.md'), '--diagrams', join(dir, 'diagrams'), ...extra], { encoding: 'utf8', stdio: 'pipe' });
    return { code: 0, out };
  } catch (e) {
    return { code: e.status, out: `${e.stdout}${e.stderr}` };
  }
}

let failures = 0;
for (const [name, [mutate, expected]] of Object.entries(mutations)) {
  const f = goodFixture();
  mutate(f);
  const { dir, mem } = materialize(f);
  // Generate STATUS.md from the pristine state first, so only the mutation can make it stale.
  let result;
  if (f.staleStatus) {
    run(dir, mem, ['--write']);
    rmSync(join(mem, 'chapters', CH, 'derivations.md'));
    result = run(dir, mem);
  } else {
    result = run(dir, mem, ['--write']);
    if (result.code === 0) result = run(dir, mem);
  }
  rmSync(dir, { recursive: true, force: true });
  const ok = expected === null ? result.code === 0 : result.code === 1 && result.out.includes(expected);
  if (!ok) failures++;
  console.log(`${ok ? '✓' : '✗'} ${name}${ok ? '' : `\n    exit ${result.code}, expected ${expected ?? 'success'}\n    ${result.out.trim().split('\n').slice(0, 4).join('\n    ')}`}`);
}
if (failures) {
  console.error(`\n${failures} memory validator test(s) failed`);
  process.exit(1);
}
console.log(`\nall ${Object.keys(mutations).length} memory validator tests passed`);
