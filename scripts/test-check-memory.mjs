/** Gives CS 11 the full learning ladder: five hints, how to recognise the concept, a check and a variation. */
function withLadder(f) {
  const item = q(f, 11);
  item.hints = [
    { kind: 'guide', text: 'What is being minimised, and over which jobs? Say it in one sentence first.' },
    { kind: 'concept', text: 'Recall what waiting time means: the time a job spends ready but not running.' },
    { kind: 'principle', text: 'Running a short job before a long one lowers the wait of everything behind it.' },
    { kind: 'setup', text: 'Write the four policies in a column and ask of each: does it look at burst length?' },
    { kind: 'partial', text: 'Only one policy uses burst length to choose; check it against the principle.' },
  ];
  item.solution = {
    ...item.solution,
    recognize: { concept: `${CH}.sjf-srtf`, clues: 'The words mean waiting time point to a policy that orders jobs by length.', contrast: 'Round robin shares the CPU but does not order by length.' },
    check: { body: 'Swap two adjacent jobs in any order and the mean wait rises, which confirms the order.' },
  };
  item.variation = { stem: 'Which policy minimises mean turnaround time for jobs all present at time zero?', options: ['FCFS', 'SJF', 'Round robin', 'LIFO'], answer: 1, explanation: 'Turnaround is wait plus burst, and the bursts are fixed, so minimising waiting minimises turnaround.' };
}

